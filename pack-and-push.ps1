<#
[CLO] pack-and-push.ps1

Packs the LiChessable extension into a signed .crx and, optionally, pushes it
to a connected Android phone so it can be sideloaded into Edge Canary
(Settings > Developer Options > "Extension install by crx").

USAGE
  .\pack-and-push.ps1            # just pack, output goes to .\dist\
  .\pack-and-push.ps1 -Push      # pack AND push to phone via adb

ONE-TIME SETUP
  Place this script in the SAME folder as manifest.json (the extension root).
  If Windows blocks the script from running, open PowerShell once and run:
    Set-ExecutionPolicy -Scope CurrentUser RemoteSigned

NOTES
  - First run generates lichessable.pem next to this script. Keep it out of
    git (add to .gitignore) and back it up — reusing it on every pack is what
    keeps the extension's ID stable across versions, so Edge treats updates
    as the same extension rather than a new install each time.
  - Requires a local Chromium-based browser (Edge, Edge Canary, or Chrome)
    for --pack-extension. If auto-detection fails, set $env:BROWSER_BIN
    yourself before running.
  - -Push requires adb (Android platform-tools) on PATH, USB debugging
    enabled, and this PC authorized on the phone.
#>

param(
    [switch]$Push
)

$ErrorActionPreference = 'Stop'

$ExtDir = $PSScriptRoot
$DistDir = Join-Path $ExtDir 'dist'
$KeyFile = Join-Path $ExtDir 'lichessable.pem'
$ManifestPath = Join-Path $ExtDir 'manifest.json'

if (-not (Test-Path $ManifestPath)) {
    Write-Error "[CLO] manifest.json not found next to this script ($ExtDir). Move the script into the extension root."
    exit 1
}

$Manifest = Get-Content $ManifestPath -Raw | ConvertFrom-Json
$Version = $Manifest.version
if (-not $Version) {
    Write-Error "[CLO] Could not read version from manifest.json."
    exit 1
}
$CrxName = "lichessable-$Version.crx"

New-Item -ItemType Directory -Force -Path $DistDir | Out-Null

# --- locate a Chromium-based browser -----------------------------------------
function Find-Browser {
    if ($env:BROWSER_BIN -and (Test-Path $env:BROWSER_BIN)) {
        return $env:BROWSER_BIN
    }

    $candidates = @(
        "$env:LOCALAPPDATA\Microsoft\Edge SxS\Application\msedge.exe",
        "${env:ProgramFiles(x86)}\Microsoft\Edge SxS\Application\msedge.exe",
        "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
        "${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
        "$env:LOCALAPPDATA\Google\Chrome\Application\chrome.exe",
        "$env:ProgramFiles\Google\Chrome\Application\chrome.exe",
        "${env:ProgramFiles(x86)}\Google\Chrome\Application\chrome.exe"
    )

    foreach ($c in $candidates) {
        if ($c -and (Test-Path $c)) {
            return $c
        }
    }

    foreach ($name in @('msedge.exe', 'chrome.exe')) {
        $cmd = Get-Command $name -ErrorAction SilentlyContinue
        if ($cmd) { return $cmd.Source }
    }

    return $null
}

$BrowserBin = Find-Browser
if (-not $BrowserBin) {
    Write-Error "[CLO] Could not find Edge or Chrome automatically. Re-run with: `$env:BROWSER_BIN='C:\path\to\msedge.exe'; .\pack-and-push.ps1"
    exit 1
}
Write-Host "[CLO] Using browser: $BrowserBin"

# --- pack ---------------------------------------------------------------------
$packArgs = @("--pack-extension=$ExtDir")
if (Test-Path $KeyFile) {
    Write-Host "[CLO] Reusing existing signing key: $KeyFile"
    $packArgs += "--pack-extension-key=$KeyFile"
} else {
    Write-Host "[CLO] No signing key found yet - one will be generated by this pack."
}

& $BrowserBin @packArgs
Start-Sleep -Milliseconds 500   # let the browser finish writing output files before we look for them

$GeneratedCrx = "$ExtDir.crx"
$GeneratedPem = "$ExtDir.pem"

if (-not (Test-Path $GeneratedCrx)) {
    Write-Error "[CLO] Packing failed - no .crx was produced at $GeneratedCrx."
    exit 1
}

Move-Item -Force $GeneratedCrx (Join-Path $DistDir $CrxName)
Write-Host "[CLO] Packed: $(Join-Path $DistDir $CrxName)"

if (Test-Path $GeneratedPem) {
    if (Test-Path $KeyFile) {
        # Shouldn't normally happen since we passed -pack-extension-key, but
        # guard against a stray duplicate key rather than silently overwrite it.
        Remove-Item -Force $GeneratedPem
    } else {
        Move-Item -Force $GeneratedPem $KeyFile
        Write-Host "[CLO] Saved new signing key: $KeyFile"
        Write-Host "[CLO]   -> add this filename to .gitignore and back it up somewhere safe."
    }
}

# --- optional push to phone ----------------------------------------------------
if ($Push) {
    $adb = Get-Command adb.exe -ErrorAction SilentlyContinue
    if (-not $adb) {
        Write-Error "[CLO] adb not found on PATH - install Android platform-tools to use -Push."
        exit 1
    }

    & adb get-state *> $null
    if ($LASTEXITCODE -ne 0) {
        Write-Error "[CLO] No device detected by adb. Check the USB cable, that USB debugging is on, and that this PC is authorized on the phone."
        exit 1
    }

    $devicePath = "/sdcard/Download/$CrxName"
    & adb push (Join-Path $DistDir $CrxName) $devicePath
    Write-Host "[CLO] Pushed to device: $devicePath"
    Write-Host "[CLO] On the phone: Edge Canary > Settings > Developer Options >"
    Write-Host "[CLO]   'Extension install by crx' > pick $CrxName from Downloads"
}
